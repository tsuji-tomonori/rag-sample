import { readFile, writeFile, mkdir } from "node:fs/promises"
import { existsSync } from "node:fs"
import path from "node:path"

const output = "docs/generated/web-inventory.md"
const source = await readFile("apps/web/src/App.tsx", "utf8")
const headings = [...source.matchAll(/<h([12])>([^<]+)<\/h\1>/g)].map(match => `| h${match[1]} | ${match[2]} |`)
const body = ["<!-- Generated by npm run docs:web. Do not edit. -->","","# Web inventory","","| Level | Label |","|---|---|",...headings,""].join("\n")
if (process.argv.includes("--check")) {
  if (!existsSync(output) || await readFile(output,"utf8") !== body) throw new Error(`${output} is stale`)
} else {
  await mkdir(path.dirname(output), { recursive:true }); await writeFile(output,body)
}

